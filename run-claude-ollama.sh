#!/bin/sh
set -eu
: "${OLLAMA_BASE_URL:?Set OLLAMA_BASE_URL to your internal Ollama server, e.g. http://192.168.1.10:11434}"
: "${OLLAMA_MODEL:?Set OLLAMA_MODEL to the exact locally installed model name}"
case "$OLLAMA_MODEL" in *:cloud) echo 'Cloud models are disabled in this launcher' >&2; exit 1;; esac
export PATH="$HOME/.local/bin:$HOME/agent-controls/bin:$PATH"
export ANTHROPIC_BASE_URL="$OLLAMA_BASE_URL"
export ANTHROPIC_AUTH_TOKEN=ollama
export ANTHROPIC_API_KEY=""
export ANTHROPIC_MODEL="$OLLAMA_MODEL"
export ANTHROPIC_DEFAULT_HAIKU_MODEL="$OLLAMA_MODEL"
export ANTHROPIC_DEFAULT_SONNET_MODEL="$OLLAMA_MODEL"
export ANTHROPIC_DEFAULT_OPUS_MODEL="$OLLAMA_MODEL"
export ANTHROPIC_SMALL_FAST_MODEL="$OLLAMA_MODEL"
export CLAUDE_CODE_SUBAGENT_MODEL="$OLLAMA_MODEL"
export DISABLE_AUTOUPDATER=1
export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1
export DISABLE_TELEMETRY=1
export DISABLE_ERROR_REPORTING=1
export DISABLE_BUG_COMMAND=1
export CLAUDE_CODE_MAX_OUTPUT_TOKENS="${CLAUDE_CODE_MAX_OUTPUT_TOKENS:-4096}"
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_HUB_DISABLE_TELEMETRY=1
exec claude --model "$OLLAMA_MODEL" "$@"
